// Builds migrations/0002_school_directory.sql from the Hipo university-domains list.
//
//   curl -sSL -o /tmp/world.json https://raw.githubusercontent.com/Hipo/university-domains-list/master/world_universities_and_domains.json
//   node scripts/build-school-seed.mjs /tmp/world.json
//
// Only `.edu` domains are kept: those are the ones that can sign in without an admin exception.
import { readFileSync, writeFileSync } from "node:fs";

const input = process.argv[2];
if (!input) {
  console.error("usage: node scripts/build-school-seed.mjs <world_universities_and_domains.json>");
  process.exit(1);
}

const list = JSON.parse(readFileSync(input, "utf8"));
const q = (v) => (v == null ? "NULL" : `'${String(v).replace(/'/g, "''")}'`);

const rows = new Map();
for (const uni of list) {
  for (const raw of uni.domains ?? []) {
    const domain = String(raw).trim().toLowerCase().replace(/^www\./, "");
    if (!domain.endsWith(".edu") || rows.has(domain)) continue;
    rows.set(domain, [domain, uni.name, uni.country ?? null, uni["state-province"] ?? null, uni.web_pages?.[0] ?? null]);
  }
}

const sorted = [...rows.values()].sort((a, b) => a[0].localeCompare(b[0]));
const chunks = [];
for (let i = 0; i < sorted.length; i += 150) {
  const values = sorted
    .slice(i, i + 150)
    .map((r) => `(${r.map(q).join(", ")})`)
    .join(",\n  ");
  chunks.push(
    "INSERT OR IGNORE INTO `school_directory` (`domain`, `name`, `country`, `state`, `web_page`) VALUES\n  " + values + ";",
  );
}

const header = `-- Generated by scripts/build-school-seed.mjs from Hipo/university-domains-list (${sorted.length} .edu domains).\n`;
writeFileSync(new URL("../migrations/0002_school_directory.sql", import.meta.url), header + chunks.join("\n--> statement-breakpoint\n") + "\n");
console.log(`wrote ${sorted.length} domains in ${chunks.length} statements`);
